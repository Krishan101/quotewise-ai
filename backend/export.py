"""
export.py — Stage 9: Draft Export (JSON / PDF)

Every export is a DRAFT. Nothing is sent anywhere.
Only READY_FOR_REVIEW lines are priced in the totals; every other line is
listed with its status and reason so nothing silently disappears.
"""

import io
from datetime import datetime, timezone
from typing import Any, Dict, List

from schemas import LineStatus, QuoteLine, RFQResponse

DRAFT_NOTICE = ("DRAFT - NOT A BINDING QUOTE. Generated by QuoteWise AI and requires human "
                "approval before sending.")


def _ascii(s: Any) -> str:
    """ReportLab's built-in fonts cannot render a few symbols; swap them for ASCII."""
    s = "" if s is None else str(s)
    for a, b in {"→": "->", "≤": "<=", "≥": ">=", "≠": "!=", "×": "x", "–": "-", "—": "-"}.items():
        s = s.replace(a, b)
    return s


def _spec(line: QuoteLine) -> str:
    n = line.normalized
    if not n:
        return ""
    parts = [n.material, n.grade, n.form]
    if n.thickness_in:
        parts.append(f'{n.thickness_in}"' + (f" ({n.gauge})" if n.gauge else ""))
    if n.width_in and n.length_in:
        parts.append(f'{n.width_in:g}" x {n.length_in:g}"')
    if n.finish:
        parts.append(n.finish)
    if n.standard:
        parts.append(n.standard)
    return " | ".join(p for p in parts if p)


def build_json(rfq: RFQResponse, audit_head: Dict[str, Any]) -> Dict[str, Any]:
    quoted, excluded = [], []
    for l in rfq.lines:
        if l.status == LineStatus.READY_FOR_REVIEW:
            quoted.append({
                "line_number": l.line_number,
                "original_text": l.original_text,
                "normalized_spec": _spec(l),
                "sku": l.match.matched_sku if l.match else None,
                "quantity": l.pricing.quantity if l.pricing else None,
                "unit": l.pricing.unit if l.pricing else None,
                "unit_price": l.pricing.unit_price if l.pricing else None,
                "total_price": l.pricing.total_price if l.pricing else None,
                "price_rationale": l.pricing.price_rationale if l.pricing else None,
                "calculation_steps": l.pricing.calculation_steps if l.pricing else [],
                "assumptions": (l.match.match_notes if l.match else [])
                               + (l.pricing.price_warnings if l.pricing else []),
                "compliance": [r.model_dump() for r in (l.compliance.requirements if l.compliance else [])],
                "human_approved": l.approved,
                "approved_by": l.approved_by,
            })
        else:
            excluded.append({
                "line_number": l.line_number,
                "original_text": l.original_text,
                "status": l.status.value,
                "reason": l.status_reason,
                "clarification_question": l.clarification_question,
            })
    return {
        "document": "DRAFT QUOTE",
        "notice": DRAFT_NOTICE,
        "demo_data_notice": rfq.demo_data_notice,
        "rfq_id": rfq.rfq_id,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "source": rfq.filename or rfq.input_type.value,
        "quoted_lines": quoted,
        "excluded_lines": excluded,
        "totals": {
            "quoted_total": round(sum(q["total_price"] or 0 for q in quoted), 2),
            "approved_total": round(sum(q["total_price"] or 0 for q in quoted if q["human_approved"]), 2),
            "lines_quoted": len(quoted),
            "lines_approved": sum(1 for q in quoted if q["human_approved"]),
            "lines_excluded": len(excluded),
        },
        "audit_trail": audit_head,
    }


def build_pdf(rfq: RFQResponse, audit_head: Dict[str, Any]) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import letter, landscape
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import inch
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    data = build_json(rfq, audit_head)
    buf = io.BytesIO()
    pagesize = landscape(letter)

    def watermark(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica-Bold", 110)
        canvas.setFillColor(colors.Color(0.85, 0.1, 0.1, alpha=0.10))
        canvas.translate(pagesize[0] / 2, pagesize[1] / 2)
        canvas.rotate(30)
        canvas.drawCentredString(0, -40, "DRAFT")
        canvas.restoreState()
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.grey)
        canvas.drawString(0.5 * inch, 0.35 * inch, _ascii(DRAFT_NOTICE + " " + rfq.demo_data_notice))
        canvas.drawRightString(pagesize[0] - 0.5 * inch, 0.35 * inch, f"Page {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(buf, pagesize=pagesize, leftMargin=0.5 * inch, rightMargin=0.5 * inch,
                            topMargin=0.5 * inch, bottomMargin=0.6 * inch,
                            title=f"DRAFT Quote {rfq.rfq_id}")
    ss = getSampleStyleSheet()
    small = ParagraphStyle("small", parent=ss["Normal"], fontSize=7.5, leading=9)
    body = ParagraphStyle("body", parent=ss["Normal"], fontSize=9, leading=11)
    P = lambda t, st=small: Paragraph(_ascii(t).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"), st)

    story = [
        Paragraph("DRAFT QUOTE - QuoteWise AI", ss["Title"]),
        P(f"RFQ {rfq.rfq_id} | Source: {data['source']} | Generated {data['generated_at']}", body),
        Spacer(1, 4),
        P(DRAFT_NOTICE, body),
        P(rfq.demo_data_notice, body),
        Spacer(1, 10),
        Paragraph("Quoted lines", ss["Heading2"]),
    ]

    if data["quoted_lines"]:
        rows = [["#", "Buyer wording", "Normalized spec", "SKU", "Qty", "Unit price", "Total", "Approved", "Why this price"]]
        for q in data["quoted_lines"]:
            rows.append([
                str(q["line_number"]), P(q["original_text"]), P(q["normalized_spec"]), P(q["sku"]),
                f"{q['quantity']:g} {q['unit']}", f"${q['unit_price']:,.2f}", f"${q['total_price']:,.2f}",
                "YES" if q["human_approved"] else "no", P(q["price_rationale"]),
            ])
        t = Table(rows, colWidths=[w * inch for w in (0.3, 1.8, 1.9, 1.3, 0.6, 0.8, 0.85, 0.6, 2.35)], repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f2937")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 7.5),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f3f4f6")]),
        ]))
        story.append(t)
        tot = data["totals"]
        story += [
            Spacer(1, 6),
            P(f"Quoted total (READY_FOR_REVIEW lines): ${tot['quoted_total']:,.2f}   |   "
              f"Human-approved total: ${tot['approved_total']:,.2f} "
              f"({tot['lines_approved']} of {tot['lines_quoted']} lines approved)", body),
        ]
    else:
        story.append(P("No lines are ready to quote.", body))

    # Assumptions and calculations
    story += [Spacer(1, 10), Paragraph("Assumptions, calculations and compliance", ss["Heading2"])]
    for q in data["quoted_lines"]:
        story.append(P(f"Line {q['line_number']} ({q['sku']})", ParagraphStyle("b", parent=body, fontName="Helvetica-Bold")))
        for s in q["calculation_steps"]:
            story.append(P(f"  - {s}"))
        for a in q["assumptions"]:
            story.append(P(f"  - {a}"))
        for c in q["compliance"]:
            story.append(P(f"  - {c['requirement']}: {c['status']}" + (" (required)" if c["required"] else " (informational)")
                           + (f" - {c['evidence']}" if c.get("evidence") else "")))

    if data["excluded_lines"]:
        story += [Spacer(1, 10), Paragraph("Lines not quoted (need action)", ss["Heading2"])]
        rows = [["#", "Buyer wording", "Status", "Reason / question for buyer"]]
        for e in data["excluded_lines"]:
            rows.append([str(e["line_number"]), P(e["original_text"]), e["status"],
                         P(e["clarification_question"] or e["reason"])])
        t = Table(rows, colWidths=[0.3 * inch, 2.6 * inch, 1.5 * inch, 5.6 * inch], repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#7f1d1d")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 7.5),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
        ]))
        story.append(t)

    story += [Spacer(1, 10),
              P(f"Audit trail: {audit_head.get('entries', 0)} hash-chained entries, chain valid = "
                f"{audit_head.get('valid')}, head hash {audit_head.get('head_hash', '')}")]

    doc.build(story, onFirstPage=watermark, onLaterPages=watermark)
    return buf.getvalue()
